const hindiCatalog: TranslationCatalog = { ...translations.hi, ...hindiAdditionalTranslations };

export function translate(value: string, language: AppLanguage): string {
  if (language === 'en') return value;

  const dictionary = language === 'hi' ? hindiCatalog : translations[language];
  const direct = dictionary[value];
  if (direct) return direct;

  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  if (!match) return value;
  const [, leading, content, trailing] = match;
  const translatedContent = dictionary[content] ?? dictionary[content.replace(/:$/, '')];
  return translatedContent ? `${leading}${translatedContent}${content.endsWith(':') ? ':' : ''}${trailing}` : value;
}
